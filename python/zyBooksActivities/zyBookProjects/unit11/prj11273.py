# Take user input
user_number = int(input("Choose a Number: "))

# Convert to number Squared
squaredNum = user_number ** 2
print(f"Your Number Squared (2nd power) is {squaredNum}")

# Convert to Number Cubed
cubedNum = user_number ** 3
print(f"Your Number Cubed (3rd power) is {cubedNum}")

# Convert to number to the 4th Power
fourthNum = user_number ** 4
print(f"Your Number to the 4th Power is {fourthNum}")